def describe(profile_id):
    """Return an isolated description; unknown IDs fail rather than guess."""
    result = deepcopy(PROFILES[profile_id])
    result.update(profile_id=profile_id, rules=list(RULES), provenance=deepcopy(PROVENANCE_CONTRACT))
    return result


def instructions(profile_id):
    """Serializable instructions for existing ingestion; not evidence itself."""
    return json.dumps(describe(profile_id), ensure_ascii=False, indent=2)


def candidates(text):
    """Paper-text routing hints only; all results require layout confirmation.

    Returns every matching profile. Does not pick a winner or inspect native EDI.
    Fallbacks are selected explicitly after inspecting visible document labels.
    """
    head = text[:32768].casefold()
    return [key for key, p in PROFILES.items()
            if any(re.search(r"(?<!\w)" + re.escape(marker.casefold()) + r"(?!\w)", head)
                   for marker in p['markers'])]


def validate_registry():
    for key, profile in PROFILES.items():
        if not key or not profile['description'] or not profile['fields']:
            raise ValueError('Incomplete profile: ' + key)
        if not all(url.startswith('https://') for url in profile['source_urls']):
            raise ValueError('Invalid source URL: ' + key)
    return len(PROFILES)


